export function PropertyTeamTab({ property }) {
  const [allPortalUsers, setAllPortalUsers] = useState([]);
  const [assignedIds, setAssignedIds] = useState(new Set());
  const [loaded, setLoaded] = useState(false);
  const [search, setSearch] = useState("");
  const [busy, setBusy] = useState(false);

  const load = async () => {
    setLoaded(false);
    const [{ data: usersData }, { data: links }] = await Promise.all([
      supabase.from("portal_users").select("*").order("name"),
      supabase
        .from("portal_user_properties")
        .select("portal_user_id")
        .eq("property_id", property.id),
    ]);
    setAllPortalUsers((usersData || []).filter((u) => u.active !== false));
    setAssignedIds(new Set((links || []).map((l) => l.portal_user_id)));
    setLoaded(true);
  };
  useEffect(() => {
    load(); /* eslint-disable-next-line */
  }, [property.id]);

  // Persist immediately on toggle.
  const onToggle = async (pid) => {
    if (busy) return;
    setBusy(true);
    const has = assignedIds.has(pid);
    // Optimistic.
    setAssignedIds((prev) => {
      const next = new Set(prev);
      if (has) next.delete(pid);
      else next.add(pid);
      return next;
    });
    const { error } = has
      ? await supabase
          .from("portal_user_properties")
          .delete()
          .eq("portal_user_id", pid)
          .eq("property_id", property.id)
      : await supabase
          .from("portal_user_properties")
          .insert({ portal_user_id: pid, property_id: property.id });
    setBusy(false);
    if (error) {
      alert("Could not update access: " + error.message);
      load(); // resync on failure
    }
  };

  return (
    <PortalUserAssignmentSection
      portalUsers={allPortalUsers}
      assignedIds={assignedIds}
      loaded={loaded}
      search={search}
      setSearch={setSearch}
      onToggle={onToggle}
      onUserCreated={(user) => {
        setAllPortalUsers((prev) =>
          [...prev, user].sort((a, b) =>
            (a.name || "").localeCompare(b.name || ""),
          ),
        );
        // A newly created user is auto-linked to this property.
        onToggle(user.id);
      }}
    />
  );
}
