export function PortalAssignmentSection({ title, subtitle, items, color, onOpen }) {
  if (items.length === 0) return null;
  const colors = {
    stone: "border-stone-300 bg-stone-50",
    amber: "border-amber-300 bg-amber-50",
    red: "border-red-300 bg-red-50",
    emerald: "border-emerald-300 bg-emerald-50",
  };
  return (
    <div>
      <div className="text-xs uppercase tracking-wider text-stone-500 font-mono mb-2">
        {title} ({items.length})
      </div>
      <p className="text-xs text-stone-500 mb-3">{subtitle}</p>
      <div className="space-y-2">
        {items.map((a) => (
          <button
            key={a.id}
            onClick={() => onOpen(a)}
            className={`w-full text-left p-4 rounded-2xl border-2 hover:border-stone-900 transition-colors ${colors[color]}`}
          >
            <div className="flex items-start justify-between gap-2">
              <div className="flex-1 min-w-0">
                <div className="flex items-center gap-2 mb-1">
                  {a.file_kind === "pdf" ? (
                    <FileText
                      size={14}
                      className="text-stone-600 flex-shrink-0"
                    />
                  ) : (
                    <ImageIcon
                      size={14}
                      className="text-stone-600 flex-shrink-0"
                    />
                  )}
                  <span className="font-serif text-base text-stone-900 truncate">
                    {a.title}
                  </span>
                </div>
                {/* Priority + cleaning-type chips so PMs see urgency
                   and what kind of clean was requested at a glance. */}
                {(a.hasPriority || a.assignment_type) && (
                  <div className="flex items-center gap-1.5 flex-wrap mb-1">
                    <PriorityChip on={a.hasPriority} />
                    <AssignmentTypeChip type={a.assignment_type} />
                  </div>
                )}
                <div className="text-xs text-stone-500 font-mono">
                  {fmtDate(a.created_at)} · {a.targets?.length || 0}{" "}
                  {a.targets?.length === 1 ? "target" : "targets"}
                </div>
                {a.pm_rejection_reason && (
                  <div className="text-xs text-red-700 italic mt-1">
                    "{a.pm_rejection_reason}"
                  </div>
                )}
              </div>
              <ChevronRight
                size={16}
                className="text-stone-400 flex-shrink-0"
              />
            </div>
          </button>
        ))}
      </div>
    </div>
  );
}
